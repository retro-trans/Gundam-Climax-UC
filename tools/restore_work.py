"""Recreate the local working files after a fresh clone (they hold Japanese text, so git only has the
*.en.json copies written by tools/strip_jp.py).

Needs the game files extracted from your own disc (see README "Build it yourself"):
  work/source/iso/SLPS_256.27, work/source/iso/MB/*.MB, work/source/game/, work/source/fpk/

python tools/restore_work.py          dry run: report what would be written
python tools/restore_work.py --write

- strings.json: re-extracted from your disc (tools/extract_text.py), then each row gets its id, English
  and notes from strings.en.json, matched by where the text lives (file + offset, or ELF address).
- cards.json, subtitles.json: copied from the .en.json files (the build only reads the English).
- textures.json: regenerated by tools/tex_jobs.py.
"""
import json
import os
import shutil
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)
TR = os.path.join(ROOT, 'work', 'translation', 'en')


def occ_key(o):
    if 'path' in o:
        return ('p', o['path'], o.get('off'), o.get('line'), o.get('rec'), o.get('cell'))
    return ('a', o.get('addr'))


def remap(fresh, en_rows):
    """fresh: rows from extract_text (jp, occ, new ids); en_rows: strings.en.json. -> rows, problems."""
    by_occ = {}
    for r in en_rows:
        for o in r.get('occ', []):
            by_occ[occ_key(o)] = r
    out, probs, used = [], [], set()
    for r in fresh:
        hits = {id(by_occ[k]): by_occ[k] for k in (occ_key(o) for o in r['occ']) if k in by_occ}
        if len(hits) != 1:
            probs.append('%s: %d English matches (%s)' % (r['id'], len(hits), r['occ'][0] if r['occ'] else '-'))
            out.append(r)
            continue
        e = next(iter(hits.values()))
        row = dict(e)
        row['jp'] = r['jp']
        row['occ'] = r['occ']
        out.append(row)
        used.add(e['id'])
    for e in en_rows:
        if e['id'] not in used:
            probs.append('%s: English row not matched to the disc' % e['id'])
    out.sort(key=lambda r: r['id'])
    return out, probs


def main(write):
    import extract_text
    done = []
    sj = os.path.join(TR, 'strings.json')
    if not os.path.exists(sj):
        tmp = sj + '.fresh'
        extract_text.OUT = tmp
        extract_text.main()
        fresh = json.load(open(tmp, encoding='utf-8'))
        os.remove(tmp)
        en_rows = json.load(open(os.path.join(TR, 'strings.en.json'), encoding='utf-8'))
        rows, probs = remap(fresh, en_rows)
        print('strings: %d rows, %d problems' % (len(rows), len(probs)))
        for p in probs[:20]:
            print('  ', p)
        if write:
            json.dump(rows, open(sj, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        done.append('strings.json')
    for name in ('cards', 'subtitles'):
        dst = os.path.join(TR, name + '.json')
        if not os.path.exists(dst):
            if write:
                shutil.copyfile(os.path.join(TR, name + '.en.json'), dst)
            done.append(name + '.json')
    if write:
        import runpy
        runpy.run_path(os.path.join(TOOLS, 'tex_jobs.py'), run_name='__main__')
    done.append('textures.json')
    print(('written: ' if write else 'would write: ') + ', '.join(done))


if __name__ == '__main__':
    main('--write' in sys.argv)
